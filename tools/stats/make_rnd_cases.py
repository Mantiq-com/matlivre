"""Writes tools/stats/cases_rnd.txt: random number generators of the univariate families."""
import os
here = os.path.dirname(os.path.abspath(__file__))
SIMPLE = {
    "unif": ["0,1", "-1,3", "[0 1 2],[1 3 6]"],
    "exp": ["1", "2.5", "[1 2 3]"],
    "wbl": ["1,1", "2,3", "[1 2 3],[0.5 1 2]"],
    "ev": ["0,1", "2,0.5", "[1 2 3],[0.5 1 2]"],
    "gev": ["0,1,0", "0.3,2,1", "[0 0.2 -0.3],[1 2 3],[0 1 2]"],
    "gp": ["0,1,0", "0.3,2,1", "[0 0.2 -0.3],[1 2 3],[0 1 2]"],
    "geo": ["0.3", "0.01", "[0.1 0.5 0.9]"],
    "unid": ["5", "100", "[3 6 9]"],
    "bino": ["10,0.3", "1,0.5", "[5 10 20],[0.2 0.5 0.9]"],
    "hyge": ["20,7,5", "[20 30 40],[7 8 9],[5 6 7]"],
}
BAD = {"unif": "2,1", "exp": "-1", "wbl": "-1,2", "ev": "0,-1", "gev": "0,-1,0", "gp": "0,-1,0",
       "geo": "2", "unid": "-1", "bino": "-1,0.3", "hyge": "5,7,2"}
lines = ["# generated by make_rnd_cases.py"]
for fam, plist in SIMPLE.items():
    for p in plist:
        scalar = "[" not in p
        if scalar:
            lines.append(f"rng(1); r = {fam}rnd({p});")
            lines.append(f"rng(2); r = {fam}rnd({p},1,6);")
            lines.append(f"rng(3); r = {fam}rnd({p},[2 3]);")
            lines.append(f"rng(4); r = {fam}rnd({p},3);")
            lines.append(f"rng(5); r = {fam}rnd({p},2,2,2);")
            lines.append(f"rng(6); r = {fam}rnd({p},[1 4],'single');")
            lines.append(f"rng(7); r = {fam}rnd(single({p.split(',')[0]}),{','.join(p.split(',')[1:]) or '1'},1,3);" if ',' in p else f"rng(7); r = {fam}rnd(single({p}),1,3);")
        else:
            lines.append(f"rng(1); r = {fam}rnd({p});")
            lines.append(f"rng(2); r = {fam}rnd({p},1,3);")
            lines.append(f"rng(3); r = {fam}rnd({p},[1 4]);")
            lines.append(f"rng(4); r = {fam}rnd({p},3,1);")
    lines.append(f"rng(1); r = {fam}rnd({BAD[fam]},[1 3]);")
    lines.append(f"rng(1); r = {fam}rnd({SIMPLE[fam][0]},-1);")
    lines.append(f"rng(1); r = {fam}rnd({SIMPLE[fam][0]},0,3);")
    lines.append(f"rng(1); r = {fam}rnd();")
    lines.append(f"rng(1); r = {fam}rnd({SIMPLE[fam][-1]},2,2);")
    lines.append(f"rng(1); r = {fam}rnd({SIMPLE[fam][0]},1.5);")
    lines.append(f"rng(1); r = {fam}rnd({SIMPLE[fam][0]},'a');")
    lines.append(f"rng(1); r = {fam}rnd({SIMPLE[fam][0]},[2 3],[1 2]);")
# normal-based generators: only the shape (sigma 0 leaves mu)
for t in ["normrnd(2,0,[2 3])", "normrnd([1 2 3],0)", "normrnd(1,0,2,2)", "normrnd(1,-1,[1 2])", "lognrnd(0,0,[1 3])", "normrnd([1 2],0,3)", "normrnd(single(1),0,[1 2])", "normrnd(1,[0 0],2,2)"]:
    lines.append(f"rng(1); r = {t};")
for t in ["rand(1,5)", "randi(10,1,6)", "randperm(8)", "rand(2,3,'single')"]:
    lines.append(f"rng(1); r = {t};")
with open(os.path.join(here, "cases_rnd.txt"), "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(lines) + "\n")
print(len(lines))
