"""Writes crates/livre-lang/src/stats/errtab.rs: the validation messages of the distribution
functions, taken from the recorded MATLAB output (stats_cases.m and stats_matlab.txt)."""
import os, re
root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
data = os.path.join(root, "crates", "livre-lang", "tests", "all", "data")
cases = [l[1:-2].replace("''", "'") for l in open(os.path.join(data, "stats_cases.m"), encoding="utf-8") if l.startswith("'")]
errs = {}
for l in open(os.path.join(data, "stats_matlab.txt"), encoding="utf-8"):
    m = re.match(r"(\d+)\|ERR\|(.*)", l.rstrip("\n"))
    if m:
        errs[int(m.group(1))] = m.group(2)
out = {}
for i, text in enumerate(cases, 1):
    if i not in errs:
        continue
    m = re.match(r"r = ([a-z0-9]+(?:pdf|cdf|inv|stat))\((.*)\);$", text)
    if not m:
        continue
    fn, args = m.groups()
    msg = errs[i]
    up = args.endswith(",'upper'")
    if args == "":
        sc = "noargs"
    elif re.fullmatch(r"\[[^\]]*\]", args):
        sc = "onlyx"
    elif "match in size" in msg or "incompatible sizes" in msg:
        sc = "mismatch_upper" if up else "mismatch"
    else:
        continue
    out[(fn, sc)] = msg
with open(os.path.join(root, "crates", "livre-lang", "src", "stats", "errtab.rs"), "w", encoding="utf-8", newline="\n") as f:
    f.write("//! Generated by tools/stats/gen_errtab.py from the recorded MATLAB output: (function, situation, message).\n\n")
    f.write("pub const ERRS: &[(&str, &str, &str)] = &[\n")
    for (fn, sc), msg in sorted(out.items()):
        f.write(f'    ("{fn}", "{sc}", "{msg}"),\n')
    f.write("];\n")
print(len(out), "entries")
