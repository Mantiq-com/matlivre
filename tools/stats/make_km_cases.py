"""Writes tools/stats/cases_km.txt: kmeans."""
import os
here = os.path.dirname(os.path.abspath(__file__))
PRE = "X12=[x(1:12)' y(1:12)']; X3=[x(1:15)' y(1:15)' x(16:30)']; S3=X12([1 5 9],:); "
L = ["# generated by make_km_cases.py"]
def four(call):
    return f"[i_,c_,s_,d_] = {call}; r = {{i_,c_,s_,d_}};"
c = []
for o in ["'Start',S3", "'Start',S3,'OnlinePhase','on'", "'Start',S3,'MaxIter',2", "'Start',S3,'MaxIter',1", "'Start',X12([2 6],:)", "'Start',X12([3 7 11 12],:),'OnlinePhase','on'",
          "'Start',S3,'Distance','cosine'", "'Start',S3,'Distance','correlation'", "'Start',S3,'Distance','sqeuclidean','OnlinePhase','on'",
          "'Start',S3,'Distance','cosine','OnlinePhase','on'", "'Start',repmat(X12(1,:),3,1)", "'Start',repmat(X12(1,:),3,1),'EmptyAction','drop'", "'Start',repmat(X12(1,:),3,1),'EmptyAction','error'",
          "'Start',repmat(X12(1,:),3,1),'EmptyAction','singleton','OnlinePhase','on'", "'Start',cat(3,S3,X12([2 6 10],:)),'Replicates',2", "'Start',cat(3,S3,X12([2 6 10],:))",
          "'Start',S3,'Display','off'"]:
    c.append(("kmeans(X12,3," + o + ")"))
c += ["kmeans(X12,1,'Start',X12(1,:))", "kmeans(X12,12,'Start',X12)", "kmeans(X12,2,'Start','uniform')", "kmeans(X12,3,'Start',S3,'Distance','hamming')", "kmeans(X12,3,'Start',S3,'Distance','foo')",
      "kmeans(X12,3,'Start','foo')", "kmeans(X12,3,'Start',S3(1:2,:))", "kmeans(X12,3,'Start',S3(:,1))", "kmeans(X12,13,'Start','sample')", "kmeans(X12,0,'Start','sample')", "kmeans(X12)", "kmeans(X12,3,'Start',S3,'Foo',1)",
      "kmeans(X12,3,'Start',S3,'Replicates',2)", "kmeans(X12,3,'Start',S3,'EmptyAction','foo')", "kmeans(X12,3,'Start',S3,'OnlinePhase','maybe')"]
for k in c:
    L.append(four(k))
# NaN rows and 3-D data
L.append(four("kmeans([X12;NaN NaN],3,'Start',S3)"))
L.append(four("kmeans(X3,3,'Start',X3([1 6 11],:))"))
L.append(four("kmeans(X3,2,'Start',X3([1 6],:),'OnlinePhase','on')"))
L.append(four("kmeans(single(X12),3,'Start',single(S3))"))
# random starts
for st in ["uniform", "sample", "plus", "cluster"]:
    for seed in [1, 2]:
        L.append(f"rng({seed}); " + four(f"kmeans(X12,3,'Start','{st}')"))
    L.append("rng(3); " + four(f"kmeans(X12,3,'Start','{st}','Replicates',3)"))
    L.append("rng(4); " + four(f"kmeans(X3,4,'Start','{st}','OnlinePhase','on')"))
L.append("rng(1); " + four("kmeans(X12,3)"))
L.append("rng(1); " + four("kmeans(X12,2,'Distance','cosine')"))
L.append("rng(1); r = randsample(12,3);")
L.append("rng(1); r = randsample(12,1);")
L.append("rng(2); r = randsample(100,5);")
L.append("rng(1); r = datasample([1 2 3 4 5 6 7 8],1);")
L.append("rng(1); r = datasample([1 2 3 4 5 6 7 8],3);")
L.append("rng(1); r = datasample([1 2 3 4 5 6 7 8],2,'Replace',false);")
L.append("rng(1); r = datasample([1 2 3 4 5 6 7 8],1,'Replace',false,'Weights',[1 2 3 4 5 6 7 8]/36);")
L.append("rng(1); r = datasample([1 2 3 4 5 6 7 8],3,'Weights',[1 2 3 4 5 6 7 8]/36);")
L = [L[0]] + [PRE + l for l in L[1:]]
with open(os.path.join(here, "cases_km.txt"), "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(L) + "\n")
print(len(L))
