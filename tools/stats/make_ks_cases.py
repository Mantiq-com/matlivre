"""Writes tools/stats/cases_ks.txt: kstest and kstest2."""
import os
here = os.path.dirname(os.path.abspath(__file__))
PRE = "s15=[-1.2 0.3 0.8 -0.4 1.9 0.1 -0.7 0.5 1.1 -2.0 0.25 0.9 -0.15 0.6 1.4]; t9=[0.2 0.9 1.5 2.1 0.4 1.1 0.7 1.8 2.6]; c3=[-3 0.001;0 0.5;3 0.999]; "
L = ["# generated by make_ks_cases.py"]
def k4(call):
    return f"[h_,p_,s_,cv_] = {call}; r = {{h_,p_,s_,cv_}};"
def k3(call):
    return f"[h_,p_,s_] = {call}; r = {{h_,p_,s_}};"
for c in ["s15", "x", "x(1:30)", "s15,'Alpha',0.1", "s15,'Tail','larger'", "s15,'Tail','smaller'", "s15,'Alpha',0.01,'Tail','unequal'", "s15,[],0.1", "s15,[],0.1,1", "s15,[],0.1,-1",
          "s15,'CDF',c3", "x(1:30),'CDF',c3", "s15+10", "x(1:100)", "x(1:100),'Tail','larger'", "x(1:150),'Alpha',0.02", "[0.5 0.5 0.5]", "[1 2]", "[1 2 NaN 3]", "x'", "s15',[1;2;3]*[0.01 0.2]", "x(1:100)*3",
          "x(1:25),'Alpha',0.005", "x(1:25),'Alpha',0.1", "x(1:25),'Alpha',0.2", "s15,'Alpha',0.001", "s15,'Tail',1", "s15,'Tail',-1", "x(1:300)"]:
    L.append(k4(f"kstest({c})"))
for c in ["s15,'Alpha',0", "s15,'Alpha',1", "s15,'Tail','foo'", "s15,'Tail',2", "s15,'CDF',[1 2 3]", "s15,'CDF',[NaN NaN]", "s15,'CDF',[1 0.5;2 0.2]", "s15,'CDF',[0 0.1;0 0.2;1 0.5]", "s15,'CDF',[0 0.1;3 0.5]",
          "[]", "NaN", "A", "'abc'", "s15,'Foo',1"]:
    L.append(f"r = kstest({c});")
for c in ["s15,t9", "t9,s15", "x,y", "x(1:30),y(1:20)", "s15,t9,'Alpha',0.1", "s15,t9,'Tail','larger'", "s15,t9,'Tail','smaller'", "s15,t9,0.1", "s15,t9,0.1,1", "s15,t9,0.1,-1", "s15,s15", "[1 2 3],[1 2 3 4]",
          "s15',t9", "[1 1 2 2],[1 2 2 3]", "[1 NaN 3],[2 4 NaN 6]", "x,y,'Alpha',0.01", "single(s15),single(t9)", "1,2", "[1 2 3],[10 11 12]"]:
    L.append(k3(f"kstest2({c})"))
for c in ["s15", "s15,[]", "[],s15", "A,s15", "s15,t9,'Alpha',2", "s15,t9,'Tail','foo'", "s15,t9,'Foo',1", "s15,t9,0", "[NaN NaN],s15", "s15,t9,0.1,3"]:
    L.append(f"r = kstest2({c});")
L = [L[0]] + [PRE + l for l in L[1:]]
with open(os.path.join(here, "cases_ks.txt"), "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(L) + "\n")
print(len(L))
