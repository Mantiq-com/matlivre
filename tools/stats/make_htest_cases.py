"""Writes tools/stats/cases_htest.txt: hypothesis tests."""
import os
here = os.path.dirname(os.path.abspath(__file__))
L = ["# generated by make_htest_cases.py"]
def four(call, fields):
    f = ",".join(f"st.{n}" for n in fields)
    return f"[h,p,ci,st] = {call}; r = {{h,p,ci,{f}}};"
def three(call):
    return f"[h,p,ci] = {call}; r = {{h,p,ci}};"
def one(call):
    return f"r = {call};"
# ttest
TT = ["ttest(A)", "ttest(x)", "ttest(v)", "ttest(A,1)", "ttest(x,0.1)", "ttest(A,2,'Alpha',0.1)", "ttest(A,2,'Tail','right')", "ttest(A,2,'Tail','left')",
      "ttest(A,2,0.01,'right')", "ttest(A,2,0.05,'left',2)", "ttest(A,2,0.05,0,2)", "ttest(A,2,0.05,1,1)", "ttest(A,[],'Dim',2)", "ttest(x',y')", "ttest(x,y)",
      "ttest(A,A.^2)", "ttest(N)", "ttest(N,1,'Dim',2)", "ttest(single(x))", "ttest([3 3 3])", "ttest([3 3 3],3)", "ttest(5)", "ttest([1 2 NaN])", "ttest([NaN NaN])",
      "ttest(A,0,'Alpha',0.2,'Tail','both')", "ttest(A,0,'tail','r')", "ttest(A,0,'Dim',1)", "ttest(1:10,5.5)", "ttest(A,1,'Alpha',0.05,'Dim',2,'Tail','left')"]
for c in TT:
    L.append(four(c, ["tstat", "df", "sd"]))
for c in ["ttest()", "ttest(A,[1 2])", "ttest(A,0,0.05)", "ttest(A,0,'Alpha',1.5)", "ttest(A,0,'Alpha',0)", "ttest(A,0,'Tail','foo')", "ttest(A,0,'Foo',1)", "ttest(A,0,'Alpha')",
          "ttest(A,0,0.05,2)", "ttest(A,0,0.05,'both',5)", "ttest('abc')", "ttest(int8([1 2 3]))", "ttest({1,2})", "ttest(A,'a')"]:
    L.append(one(c))
# ttest2
