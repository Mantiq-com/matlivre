"""Writes tools/stats/cases_lm.txt: fitlm and the LinearModel object (matrix input)."""
import os
here = os.path.dirname(os.path.abspath(__file__))
PRE = "X2=A(:,2:3); y6=A(:,1); X1=x(1:12)'; y12=y(1:12)'; X3=[x(1:15)' y(1:15)' x(16:30)']; y15=cos(0.4*(1:15))'+0.1*sin(2*(1:15))'; "
L = ["# generated by make_lm_cases.py"]
PROPS = ("m_.Coefficients.Estimate,m_.Coefficients.SE,m_.Coefficients.tStat,m_.Coefficients.pValue,m_.Rsquared.Ordinary,m_.Rsquared.Adjusted,m_.MSE,m_.RMSE,m_.SSE,m_.SST,m_.SSR,m_.DFE,"
         "m_.NumObservations,m_.NumCoefficients,m_.NumPredictors,m_.NumVariables,m_.CoefficientCovariance,m_.Fitted,m_.Residuals.Raw,m_.Residuals.Pearson,m_.Residuals.Studentized,"
         "m_.Residuals.Standardized,m_.LogLikelihood,m_.ModelCriterion.AIC,m_.ModelCriterion.AICc,m_.ModelCriterion.BIC,m_.ModelCriterion.CAIC,m_.Diagnostics.Leverage,"
         "m_.Diagnostics.CooksDistance,m_.Diagnostics.Dffits,m_.Diagnostics.S2_i,m_.Diagnostics.CovRatio,m_.Diagnostics.Dfbetas,m_.Diagnostics.HatMatrix,strjoin(m_.CoefficientNames,','),"
         "char(m_.Formula),m_.ModelFitVsNullModel.Fstat,m_.ModelFitVsNullModel.Pvalue")
def full(call):
    return f"m_ = {call}; r = {{{PROPS}}};"
specs = [("X2,y6", ""), ("X2,y6,'interactions'", ""), ("X1,y12", ""), ("X1,y12,'quadratic'", ""), ("X1,y12,'purequadratic'", ""), ("X1,y12,'poly3'", ""),
         ("X3,y15", ""), ("X3,y15,'interactions'", ""), ("X3,y15,'purequadratic'", ""), ("X3,y15,'quadratic'", ""), ("X3(:,1:2),y15,'poly21'", ""), ("X3(:,1:2),y15,'poly12'", ""),
         ("X1,y12,'Intercept',false", ""), ("X3,y15,'linear','Intercept',false", ""), ("X1,y12,'VarNames',{'age','weight'}", ""),
         ("X1,y12'", "")]
for call, _ in specs:
    L.append(full(f"fitlm({call})"))
for call in ["fitlm(X2,y6)", "fitlm(X2,y6,'interactions')", "fitlm(X1,y12)", "fitlm(X1,y12,'quadratic')", "fitlm(X3,y15)", "fitlm(X3,y15,'interactions')", "fitlm(X1,y12,'Intercept',false)", "fitlm(X1,y12,'constant')",
             "fitlm(X1,y12,'VarNames',{'age','weight'})"]:
    L.append(f"m_ = {call}; r = evalc('m_');")
for call in ["predict(m_,[1 2;3 4])", "predict(m_,[1 2;3 4],'Alpha',0.1)", "predict(m_,[1 2;3 4],'Prediction','observation')", "predict(m_,X2)", "predict(m_,[1 2])"]:
    L.append(f"m_ = fitlm(X2,y6); [a_,b_] = {call}; r = {{a_,b_}};")
    L.append(f"m_ = fitlm(X2,y6,'interactions'); [a_,b_] = {call}; r = {{a_,b_}};")
L += ["m_ = fitlm(X1,y12,'quadratic'); [a_,b_] = predict(m_,(1:3)'); r = {a_,b_};", "m_ = fitlm(X2,y6); [a_,b_] = feval(m_,[1;3],[2;4]); r = {a_,b_};", "m_ = fitlm(X1,y12); r = feval(m_,[0.5;1]);",
      "m_ = fitlm(X2,y6); r = coefCI(m_);", "m_ = fitlm(X2,y6); r = coefCI(m_,0.1);", "m_ = fitlm(X1,y12,'quadratic'); r = coefCI(m_,0.01);", "m_ = fitlm(X2,y6); r = predict(m_,[1 2 3]);",
      "r = fitlm(X2,y6(1:5));", "r = fitlm(X2);", "r = fitlm();", "r = fitlm(X2,y6,'foo');", "r = fitlm(X2,y6,'Intercept');", "r = fitlm(X1,y12,'poly9');",
      "m_ = fitlm(X2,y6); r = class(m_);", "m_ = fitlm(X2,y6); r = m_.NumObservations + 1;", "m_ = fitlm(X2,y6); m_.MSE = 1;"]
L = [L[0]] + [PRE + l for l in L[1:]]
with open(os.path.join(here, "cases_lm.txt"), "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(L) + "\n")
print(len(L))
