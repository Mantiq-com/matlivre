"""Writes tools/stats/cases_pca.txt: principal components and related decompositions."""
import os
here = os.path.dirname(os.path.abspath(__file__))
L = ["# generated by make_pca_cases.py"]
def six(call):
    return f"[c_,s_,l_,t_,e_,m_] = {call}; r = {{c_,s_,l_,t_,e_,m_}};"
D2 = "[x(1:20);y(1:20)]'"
for d in ["A", "P", D2, "A(1:4,:)", "A(1:3,:)", "A(:,1:2)", "single(A)", "x(1:10)'", "A(1:2,:)"]:
    L.append(six(f"pca({d})"))
for o in ["'Algorithm','eig'", "'Algorithm','svd'", "'Centered',false", "'Centered','off'", "'NumComponents',2", "'NumComponents',1", "'Economy',false", "'Economy','off'", "'Rows','complete'",
          "'VariableWeights','variance'", "'VariableWeights',[1 2 3 4 5]", "'Weights',[1 2 3 4 5 6]", "'Weights',[1 2 3 4 5 6],'VariableWeights',[2 1 1 1 3]",
          "'Algorithm','eig','Centered',false", "'Algorithm','eig','NumComponents',3", "'Algorithm','eig','VariableWeights','variance'", "'Algorithm','eig','Weights',[1 2 3 4 5 6]",
          "'Centered',false,'NumComponents',2", "'Economy',false,'Algorithm','eig'"]:
    L.append(six(f"pca(A,{o})"))
for o in ["'Economy',false", "'Algorithm','eig'", "'Algorithm','eig','Economy',false", "'Centered',false"]:
    L.append(six(f"pca(A(1:4,:),{o})"))
L += [six("pca(N)"), six("pca(N,'Rows','complete')"), six("pca(N,'Rows','pairwise')"), six("pca(N,'Algorithm','eig','Rows','pairwise')"), six("pca(N,'Rows','all')"),
      six("pca(5)"), six("pca([])"), six("pca(NaN(3,2))"), six("pca(zeros(4,3))"), six("pca([1 2 3])"), six("pca([1 1;1 1;1 1])"),
      "r = pca(A,'NumComponents',0);", "r = pca(A,'NumComponents',6);", "r = pca(A,'NumComponents',1.5);", "r = pca(A,'Algorithm','foo');", "r = pca(A,'Rows','foo');", "r = pca(A,'Foo',1);",
      "r = pca(A,'Weights',[1 2 3]);", "r = pca(A,'Weights',[1 2 3 4 5 -6]);", "r = pca(A,'VariableWeights',[1 2 3]);", "r = pca(A,'VariableWeights','foo');", "r = pca(A,'Centered','maybe');",
      "r = pca();", "r = pca(int8([1 2;3 4;5 7]));", "r = pca(A,'NumComponents');", "r = pca({1});", "r = pca('abc');"]
# pcacov
for c in ["cov(A)", "cov(P)", "cov(x(1:20)')", "eye(3)", "[2 1;1 2]", "diag([3 2 1])", "single(cov(A))"]:
    L.append(f"[c_,l_,e_] = pcacov({c}); r = {{c_,l_,e_}};")
L += ["r = pcacov([1 2;2 1]);", "r = pcacov([1 2 3]);", "r = pcacov(zeros(2));", "r = pcacov(1);", "r = pcacov(-eye(2));", "r = pcacov();"]
# pcares
for c in ["pcares(A,1)", "pcares(A,2)", "pcares(A,5)", "pcares(A,3)", "pcares(P,4)", "pcares(A,0)", "pcares(A,6)", "pcares(A,[1 2])", "pcares(single(A),2)", "pcares(A(1:3,:),2)", "pcares(A(1:3,:),5)"]:
    L.append(f"[rs_,rc_] = {c}; r = {{rs_,rc_}};")
# cmdscale
for c in ["cmdscale(pdist(A))", "cmdscale(squareform(pdist(A)))", "cmdscale(squareform(pdist(A)),2)", "cmdscale(squareform(pdist(A)),1)", "cmdscale(pdist(P(1:5,:)),3)", "cmdscale(pdist(A),6)",
          "cmdscale(pdist(A),7)", "cmdscale(pdist(A),0)", "cmdscale(pdist(A(:,1)))", "cmdscale(pdist(A(1:3,:),'cityblock'))", "cmdscale(1-squareform(pdist(A))/10)", "cmdscale([0 1;2 0])", "cmdscale(zeros(3))",
          "cmdscale(ones(3))", "cmdscale(single(squareform(pdist(A))))", "cmdscale([1 2 3 4])", "cmdscale(-pdist(A))", "cmdscale(pdist(A),[1 2])", "cmdscale(pdist(A),1.5)"]:
    L.append(f"[Y_,e_] = {c}; r = {{Y_,e_}};")
# corrcov
L += ["r = corrcov(cov(A));", "[R_,s_] = corrcov(cov(P)); r = {R_,s_};", "r = corrcov([4 2;2 9]);", "r = corrcov([4 2;2 1]);", "r = corrcov([4 2;2 1],1);", "r = corrcov([1 2;3 4],1);", "r = corrcov(4);", "r = corrcov(single(cov(A)));",
      "r = corrcov([1 2 3]);", "r = corrcov(zeros(2));", "r = corrcov([4 0;0 0],1);", "r = corrcov();"]
with open(os.path.join(here, "cases_pca.txt"), "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(L) + "\n")
print(len(L))
