"""Writes tools/stats/cases_fit.txt: closed-form fitting functions."""
import os
here = os.path.dirname(os.path.abspath(__file__))
PRE = "d20=abs(x(1:20)')+0.1; e20=abs(y(1:20))+0.05; k8=[3 5 4 6 2 5 4 3]; "
L = ["# generated by make_fit_cases.py"]
def two(call):
    return f"[a_,b_] = {call}; r = {{a_,b_}};"
def four(call):
    return f"[a_,b_,c_,d_] = {call}; r = {{a_,b_,c_,d_}};"
for c in ["d20", "d20,0.1", "A", "A,0.2", "x", "x'", "5", "[1 1 1]", "[1 NaN 3]", "[]", "single(d20)", "d20,[]", "A(:,1)"]:
    L.append(four(f"normfit({c})"))
for c in ["d20,0.05,zeros(20,1)", "d20,0.05,[],ones(20,1)", "d20,0.05,[],[2;ones(19,1)]", "A,0.05,zeros(6,5)", "d20,0.05,ones(3,1)", "d20,0.05,[],ones(3,1)"]:
    L.append(four(f"normfit({c})"))
L += ["r = normfit();", "[a_] = normfit(d20); r = a_;", "[a_,b_] = normfit(d20); r = {a_,b_};"]
for c in ["d20", "d20,0.1", "A", "e20", "single(d20)", "[1 2 3]", "5", "A(:,1)'"]:
    L.append(two(f"expfit({c})"))
L += ["r = expfit(-d20);", "r = expfit([]);", "r = expfit(d20,0.05,zeros(20,1));", "r = expfit();"]
for c in ["k8", "k8'", "k8,0.1", "A.^2", "round(A.^2)", "0", "[0 0 0]", "int8(k8)", "single(k8)"]:
    L.append(two(f"poissfit({c})"))
L += ["r = poissfit(-k8);", "r = poissfit();"]
for c in ["3,10", "[3 5 7],10", "[3 5 7],[10 12 14]", "[3 5 7],[10 12 14],0.1", "0,10", "10,10", "3,10,0.01", "[3 5 7]',[10 12 14]'", "single(3),10"]:
    L.append(two(f"binofit({c})"))
L += ["r = binofit(11,10);", "r = binofit(-1,10);", "r = binofit(3,-1);", "r = binofit(3,10.5);", "r = binofit([1 2;3 4],10);", "r = binofit([1 2],[3 4 5]);", "r = binofit();"]
for c in ["d20", "d20,0.1", "e20", "single(d20)", "[1 2 3]", "5"]:
    L.append(two(f"lognfit({c})"))
L += ["r = lognfit(-d20);", "r = lognfit([1 0 2]);", "r = lognfit(A);", "r = lognfit();"]
for c in ["d20", "d20,0.1", "e20", "[1 2 3]", "A", "single(d20)", "5"]:
    L.append(four(f"unifit({c})"))
for c in ["d20", "d20,0.1", "e20", "[1 2 3]", "5", "single(d20)", "d20'"]:
    L.append(two(f"raylfit({c})"))
L += ["r = raylfit(A);", "r = raylfit();"]
# likelihood functions
for c in ["[0.1 1.2],d20'", "[0.1 1.2],x", "[0 1],x", "[0.1 -1],x", "[0.5 2],d20,zeros(1,20)", "[0.1 1.2],d20,[],ones(1,20)", "[0.1 1.2],x(1:5)", "[0.1 1.2],[]"]:
    L.append(two(f"normlike({c})"))
for c in ["[0.1 1.2],d20", "[0.1 1.2],-d20", "[0.1 1.2],[1 2 NaN]", "[-1 1],d20"]:
    L.append(two(f"lognlike({c})"))
for c in ["2.5,d20", "0.7,d20", "-1,d20", "2.5,d20,zeros(1,20)", "1,[1 2 3]"]:
    L.append(two(f"explike({c})"))
L += ["r = normlike();", "r = normlike(1,x);", "r = lognlike([1 2 3],x);", "r = explike();"]
L = [L[0]] + [PRE + l for l in L[1:]]
with open(os.path.join(here, "cases_fit.txt"), "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(L) + "\n")
print(len(L))
