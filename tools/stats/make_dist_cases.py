"""Writes tools/stats/cases_dist.txt: calls of the univariate distribution functions
(pdf, cdf, inv, stat, like, fit, rnd) for the families listed below. Run it, then gen_cases.py."""
import os

here = os.path.dirname(os.path.abspath(__file__))

# name: (parameter sets (valid), x grid, probability grid, functions, discrete)
F = {
    "norm": (["0,1", "[1 2 -1],[2 .5 3]", "2,0.7"], "[-2.5 -1 0 0.3 1 2.5 4]", "discrete" and False),
}

CONT_X = "[-2.5 -1 0 0.3 1 2.5 4]"
POS_X = "[0 0.1 0.5 1 2 3.5 8]"
UNIT_X = "[0 0.05 0.3 0.5 0.8 0.95 1]"
INT_X = "[-1 0 1 2 3 5 8]"
PROBS = "[0 0.01 0.2 0.5 0.75 0.99 1]"

# family: (valid parameter lists, x grid, functions)
FAMS = {
    "norm": (["0,1", "2,0.7", "[1 2 -1],[2 .5 3]"], CONT_X, "pdf cdf inv stat like fit rnd"),
    "logn": (["0,1", "0.5,0.7", "[1 2],[2 .5]"], POS_X, "pdf cdf inv stat like fit rnd"),
    "exp": (["1", "2.5", "[1 2 4]"], POS_X, "pdf cdf inv stat like fit rnd"),
    "unif": (["0,1", "-1,3", "[0 1],[2 5]"], "[-1 0 0.3 1 2.5 4]", "pdf cdf inv stat fit rnd"),
    "gam": (["1,1", "2,3", "0.5,2", "[1 2],[3 0.5]"], POS_X, "pdf cdf inv stat like fit rnd"),
    "beta": (["1,1", "2,3", "0.5,0.5", "[1 2],[3 0.5]"], UNIT_X, "pdf cdf inv stat like fit rnd"),
    "chi2": (["1", "4", "[1 2 10]"], POS_X, "pdf cdf inv stat rnd"),
    "t": (["1", "5", "[1 2 30]"], CONT_X, "pdf cdf inv stat rnd"),
    "f": (["1,1", "3,7", "[2 5],[4 10]"], POS_X, "pdf cdf inv stat rnd"),
    "wbl": (["1,1", "2,3", "0.5,2", "[1 2],[3 0.5]"], POS_X, "pdf cdf inv stat like fit rnd"),
    "rayl": (["1", "2.5", "[1 2 4]"], POS_X, "pdf cdf inv stat fit rnd"),
    "ev": (["0,1", "1,2", "[0 1],[2 .5]"], CONT_X, "pdf cdf inv stat like fit rnd"),
    "gev": (["0,1,0", "0.3,1,0", "-0.3,2,1", "[0 0.2],[1 2],[0 1]"], CONT_X, "pdf cdf inv stat like fit rnd"),
    "gp": (["0,1,0", "0.3,1,0", "-0.3,2,0", "[0 0.2],[1 2],[0 0]"], POS_X, "pdf cdf inv stat like fit rnd"),
    "bino": (["10,0.3", "1,0.5", "[5 10],[0.2 0.9]"], INT_X, "pdf cdf inv stat fit rnd"),
    "poiss": (["1", "4.5", "[1 2 10]"], INT_X, "pdf cdf inv stat fit rnd"),
    "geo": (["0.3", "0.5", "[0.1 0.9]"], INT_X, "pdf cdf inv stat fit rnd"),
    "nbin": (["3,0.4", "1,0.5", "[2 5],[0.5 0.1]"], INT_X, "pdf cdf inv stat fit rnd"),
    "hyge": (["20,7,5", "10,10,3", "[10 20],[3 7],[2 5]"], INT_X, "pdf cdf inv stat rnd"),
    "unid": (["5", "10", "[3 8]"], INT_X, "pdf cdf inv stat rnd"),
}

# parameters that are invalid for the family (the result is NaN, not an error)
BAD = {
    "norm": "0,-1", "logn": "0,-1", "exp": "-1", "unif": "2,1", "gam": "-1,1", "beta": "-1,2", "chi2": "-1", "t": "-1", "f": "-1,2",
    "wbl": "-1,2", "rayl": "-1", "ev": "0,-1", "gev": "0,-1,0", "gp": "0,-1,0", "bino": "-1,0.3", "poiss": "-1", "geo": "2", "nbin": "-1,0.3",
    "hyge": "5,7,2", "unid": "-1",
}

lines = ["# generated by make_dist_cases.py: univariate distributions"]
for fam, (plist, xs, funcs) in FAMS.items():
    funcs = funcs.split()
    bad = BAD[fam]
    for p in plist:
        if "pdf" in funcs:
            lines.append(f"r = {fam}pdf({xs},{p});")
        if "cdf" in funcs:
            lines.append(f"r = {fam}cdf({xs},{p});")
            lines.append(f"r = {fam}cdf({xs},{p},'upper');")
        if "inv" in funcs:
            lines.append(f"r = {fam}inv({PROBS},{p});")
        if "stat" in funcs:
            lines.append(f"[m,v] = {fam}stat({p}); r = {{m,v}};")
    lines.append(f"r = {fam}pdf(NaN,{plist[0]});")
    if "pdf" in funcs:
        lines.append(f"r = {fam}pdf({xs},{bad});")
        lines.append(f"r = {fam}pdf(single({xs}),{plist[0]});")
        lines.append(f"r = {fam}pdf({xs}',{plist[0]});")
        lines.append(f"r = {fam}pdf([{xs}; {xs}],{plist[0]});")
        lines.append(f"r = {fam}pdf({xs});")
    if "cdf" in funcs:
        lines.append(f"r = {fam}cdf({xs},{bad});")
        lines.append(f"r = {fam}cdf(single({xs}),{plist[0]});")
        lines.append(f"r = {fam}cdf({xs},{plist[0]},'foo');")
    if "inv" in funcs:
        lines.append(f"r = {fam}inv({PROBS},{bad});")
        lines.append(f"r = {fam}inv([-0.1 1.1 NaN],{plist[0]});")
        lines.append(f"r = {fam}inv(single({PROBS}),{plist[0]});")
    if "stat" in funcs:
        lines.append(f"[m,v] = {fam}stat({bad}); r = {{m,v}};")
        lines.append(f"r = {fam}stat();")
    # mismatched sizes
    if "[" in plist[-1]:
        lines.append(f"r = {fam}pdf([1 2 3 4 5 6 7],{plist[-1]});")
    if "like" in funcs:
        lines.append(f"r = {fam}like([{plist[0]}],{xs.replace('[', '[').replace(']', ']')}(:)+0);")

with open(os.path.join(here, "cases_dist.txt"), "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(lines) + "\n")
print(len(lines), "lines")
