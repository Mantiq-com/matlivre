"""Writes tools/stats/cases_t11.txt: anova2 and friedman."""
import os
here = os.path.dirname(os.path.abspath(__file__))
PRE = "fr=[x(1:12)' y(1:12)' x(13:24)']+repmat([0 0.5 1],12,1); fr2=[fr; fr+0.3*[x(25:36)' y(25:36)' x(37:48)']]; "
L = ["# generated by make_t11_cases.py"]
def add(cs, fmt):
    for c in cs:
        L.append(fmt.replace("{c}", c))
t3 = "[p_,t_,s_] = {c}; sc_ = struct2cell(s_); r = [{p_}, t_(:)', sc_(:)'];"
add(["friedman(fr,1,'off')", "friedman(fr(1:12,:),2,'off')", "friedman(fr,1)", "friedman(fr(:,1),1,'off')", "friedman(fr,0,'off')", "friedman(fr,1,'foo')", "friedman([fr;NaN 1 2],1,'off')", "friedman(fr(:,1:2),1,'off')", "friedman(single(fr),1,'off')", "friedman(fr(1:12,:),1.5,'off')", "friedman(ones(4,3),1,'off')",
     "friedman(fr(1:6,:),3,'off')", "friedman(fr(1:6,:),2,'off')", "friedman(round(fr*3),1,'off')", "friedman(fr2,2,'off')", "friedman(fr2,4,'off')"], t3)
add(["anova2(fr,1,'off')", "anova2(fr,1)", "anova2(fr2,2,'off')", "anova2(fr2(1:24,:),2,'off')", "anova2(fr(1:6,:),3,'off')", "anova2(fr,0,'off')", "anova2(fr,1,'foo')", "anova2([fr;NaN 1 2],1,'off')", "anova2(fr(:,1:2),1,'off')", "anova2(fr(1:12,:),5,'off')", "anova2(single(fr),1,'off')", "anova2(fr2,3,'off')", "anova2(fr2,2)", "anova2(fr2(:,1:2),2,'off')", "anova2(fr(1:4,:),2,'off')", "anova2(round(fr*3),1,'off')", "anova2(fr)"], t3)
L = [L[0]] + [PRE + l for l in L[1:]]
with open(os.path.join(here, "cases_t11.txt"), "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(L) + "\n")
print(len(L))
